"""Orderbook-only leg-SL formula verifier — §1 + §2 of leg_sl_test_scenarios.

Implements Part B of ``leg_sl_test_scenarios.html``: the engine runs a real
backtest using EMA Cross *only as an entry trigger*, then every leg stop-loss is
verified **purely from the orderbook** — no engine internals are read.

For each closed trade whose ``EXIT REASON == "Stop Loss"`` the verifier:

1. Parses ``EXIT DETAILED REASON`` for the engine's computed SL, the entry it
   logged, the trigger side (``≤`` long / ``≥`` short) and — for atr SLs — the
   ATR used at entry (``[atr@entry=…]``).
2. Recomputes the *expected* SL from the row's ``ENTRY PRICE`` using the
   type formula and snaps it to the instrument tick.
3. Asserts ``expected_sl == engine_sl`` to within half a tick, and that the
   trigger side matches the trade direction.

Coverage (the user's selected scope):
* §1 — percentage / points / none golden fixtures (LS-PCT / LS-PTS / LS-NONE).
* §1 + §2 — atr fixtures and the ATR multiplier sweep (period 14 ×
  mult 1.0 / 1.5 / 2.0 / 3.0), plus a monotonicity check that the mean SL
  distance widens with the multiplier.

Trailing (§3 / §5 TM-01), the asset×timeframe matrix (§5) and MIS/NRML (§4,
blocked on TBD-7) are out of scope for this pass.

Output: ``5. Logics/sl_formula_tests/``
  * ``sl_formula_results.json``  — raw per-scenario summaries
  * ``portfolios/*.json``        — the saved portfolio for each scenario
  * ``sl_formula_report.html``   — generated by the companion report script

Run from the project root::

    python verify_leg_sl_formulas.py
    python tests\\smoke_tests\\verify_leg_sl_formulas_report.py
"""

